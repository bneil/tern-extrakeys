#!/usr/bin/env python3
"""Embeds the plugin entry sources as Luau strings, because the luau CLI has
no file I/O: tests/_sources.luau returns { ["host.luau"] = "...", ... }."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
files = ["host.luau", "window.luau", "hello/host.luau", "hello/window.luau"]
out = ["-- generated by tests/embed.py; do not edit", "return {"]
for f in files:
    src = (root / f).read_text()
    eq = "="
    while f"]{eq}]" in src or f"[{eq}[" in src:
        eq += "="
    out.append(f'\t["{f}"] = [{eq}[\n{src}]{eq}],')
out.append("}")
(root / "tests" / "_sources.luau").write_text("\n".join(out) + "\n")
